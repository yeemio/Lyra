/** 六类事件类型（五类公告驱动 + 一类财务驱动）。 */
export type EventType =
  | 'EARNINGS_FORECAST' // 业绩预告（含更正子类，ASHARE-RULES §9 / R10）
  | 'EARNINGS_FLASH' // 业绩快报（更正只走 supersedes，不触发新实例）
  | 'PERIOD_GROWTH_DELTA' // 定期报告增速变化（FINANCIAL 事实驱动，非标题）
  | 'SHARE_UNLOCK' // 限售解禁
  | 'HOLDER_TRADE' // 大股东增减持
  | 'BUYBACK'; // 回购

/** 单归属优先级（派发冻结）：预告 > 快报 > 解禁 > 增减持 > 回购；多命中记录次命中。 */
export const EVENT_TYPE_PRIORITY: readonly EventType[] = [
  'EARNINGS_FORECAST',
  'EARNINGS_FLASH',
  'SHARE_UNLOCK',
  'HOLDER_TRADE',
  'BUYBACK',
];

export interface AnnouncementRule {
  type: EventType;
  /** 全部正则都须命中才候选（include 数量 ≥1：第一项为主词，其余为共现要求）。 */
  include: readonly RegExp[];
  /** 任一命中即拒绝该类型。 */
  exclude: readonly RegExp[];
  /** 抽样证据与排除理由（真实标题锚定，便于 P4 复核）。 */
  evidence: string;
}

